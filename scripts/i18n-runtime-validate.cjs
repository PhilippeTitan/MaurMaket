#!/usr/bin/env node
/**
 * Localization V1 — Runtime Validation
 * =====================================
 * Exercises the REAL localization modules (adapter, languageManager,
 * providers) the same way the app does — no mocking of the logic under
 * test. Only the RN platform seam is stubbed:
 *
 *   - react-native  → Platform.OS getter + storage backends
 *   - expo-secure-store → in-memory SecureStore stand-in
 *
 * Covers the runtime-pass checklist:
 *   1. Language switching (en → ht → fr → en)
 *   2. Persistence (web localStorage path + native SecureStore path,
 *      restart simulated via fresh module require + languageManager.init())
 *   3. Parameterized translations ({name}, {count}, {age}...)
 *   4. Fallback chain: current language → English (provider) → raw key
 *   5. Module-level factory pattern (signup wizard shape)
 *   6. Raw-key leak invariant (key-shaped strings must never BE values)
 *   7. No empty translation values
 *
 * Usage: node scripts/i18n-runtime-validate.cjs
 * Exit 0 = all pass, exit 1 = failures listed.
 */
const fs = require('fs');
const path = require('path');
const Module = require('module');

const ROOT = path.resolve(__dirname, '..');
let passed = 0;
let failed = 0;
const failures = [];

function check(name, cond, detail) {
  if (cond) { passed++; console.log(`  ok    ${name}`); }
  else { failed++; failures.push({ name, detail }); console.log(`  FAIL  ${name}${detail ? ' — ' + detail : ''}`); }
}

// ── Platform seam ───────────────────────────────────────────────
// Mutable runtime state the tests flip between web / native.
// Backed by global so it survives require-cache purges.
global.__MM_SEAM_OS = 'web';
const seam = { get os() { return global.__MM_SEAM_OS; }, set os(v) { global.__MM_SEAM_OS = v; } };

function makeStorage() {
  const map = new Map();
  return {
    getItem: (k) => (map.has(k) ? map.get(k) : null),
    setItem: (k, v) => { map.set(k, String(v)); },
    removeItem: (k) => { map.delete(k); },
    _map: map,
  };
}
const webStorage = makeStorage();
const secureStore = {
  getItemAsync: async (k) => secureStore._map.has(k) ? secureStore._map.get(k) : null,
  setItemAsync: async (k, v) => { secureStore._map.set(k, String(v)); },
  _map: new Map(),
};

// web path reads GLOBAL localStorage
global.localStorage = webStorage;

// ── Module interception ─────────────────────────────────────────────
const rnStubPath = path.join(ROOT, 'scripts', '.rn-stub.cjs');
fs.writeFileSync(rnStubPath, `
// Auto-generated by i18n-runtime-validate.cjs — do not edit
const seam = require('./.rn-seam.cjs');
module.exports = {
  Platform: {
    get OS() { return seam.os; },
    select: (o) => o[seam.os] ?? o.default,
  },
  AsyncStorage: null,
  NativeModules: {},
  TurboModuleRegistry: { getEnforcing: () => ({}), get: () => ({}) },
};
`);
const seamPath = path.join(ROOT, 'scripts', '.rn-seam.cjs');
fs.writeFileSync(seamPath, 'module.exports = { get os() { return global.__MM_SEAM_OS || "web"; }, set os(v) { global.__MM_SEAM_OS = v; } };\n');

const seamModule = require('./.rn-seam.cjs');

const secureStoreStubPath = path.join(ROOT, 'scripts', '.rn-securestore-stub.cjs');
fs.writeFileSync(secureStoreStubPath, `
// Auto-generated by i18n-runtime-validate.cjs — do not edit
// .rn-seam-securestore.cjs exports a bare Map (shared via global)
const map = require('./.rn-seam-securestore.cjs');
module.exports = {
  getItemAsync: async (k) => (map.has(k) ? map.get(k) : null),
  setItemAsync: async (k, v) => { map.set(k, String(v)); },
};
`);
const ssStorePath = path.join(ROOT, 'scripts', '.rn-seam-securestore.cjs');
fs.writeFileSync(ssStorePath, 'module.exports = global.__MM_SS_MAP || (global.__MM_SS_MAP = new Map());\n');
// Seed the shared map BEFORE the stub module is ever required, so the
// stub's self-reference binds to this instance.
if (!global.__MM_SS_MAP) global.__MM_SS_MAP = new Map();
const ssStore = require('./.rn-seam-securestore.cjs');

const origResolve = Module._resolveFilename;
Module._resolveFilename = function (request, ...args) {
  if (request === 'react-native') return rnStubPath;
  if (request === 'expo-secure-store') return secureStoreStubPath;
  if (request.startsWith('@/')) {
    request = path.join(ROOT, 'src', request.slice(2));
    return origResolve.call(this, request, ...args);
  }
  return origResolve.call(this, request, ...args);
};

// TS loader (uses typescript if available — it is, via tsconfig deps)
const ts = require('typescript');
require.extensions['.ts'] = function (module, filename) {
  const src = fs.readFileSync(filename, 'utf8');
  const out = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, esModuleInterop: true },
    fileName: filename,
  });
  module._compile(out.outputText, filename);
};

// ── Helpers to load localization fresh ──────────────────────────────
function purgeLocalizationCache() {
  for (const f of Object.keys(require.cache)) {
    if (f.includes(path.join('src', 'localization')) || f.includes('.rn-stub') || f.includes('.rn-seam')) {
      delete require.cache[f];
    }
  }
}

function loadLocalization() {
  const index = require(path.join(ROOT, 'src/localization/index.ts'));
  const lm = require(path.join(ROOT, 'src/localization/languageManager.ts'));
  return { index, lm };
}

(async () => {
  // ══════════════════════════════════════════════════════════════
  console.log('\n[web storage path — Platform.OS = web]');
  seam.os = 'web';
  purgeLocalizationCache();
  const { index: L1, lm: LM1 } = loadLocalization();
  const t1 = L1.i18n.t.bind(L1.i18n);
  const setLang1 = L1.i18n.setLanguage.bind(L1.i18n);

  // 1. Language switching
  console.log('\n[1] Language switching en → ht → fr → en');
  await setLang1('en');
  check('en: settings.notifications', t1('settings.notifications') === 'Notifications', `got ${JSON.stringify(t1('settings.notifications'))}`);

  await setLang1('ht');
  check('ht: settings.notifications', t1('settings.notifications') === 'Notifikasyon', `got ${JSON.stringify(t1('settings.notifications'))}`);

  await setLang1('fr');
  check('fr: settings.notifications', t1('settings.notifications') === 'Notifications', `got ${JSON.stringify(t1('settings.notifications'))}`);

  await setLang1('en');
  check('switch back to en restores English', t1('settings.notifications') === 'Notifications');

  // Language manager getter tracks current language
  check('languageManager.language getter tracks state', LM1.languageManager.language === 'en');

  // 2. Persistence — web path
  console.log('\n[2] Persistence — web (localStorage), restart simulated');
  await setLang1('fr');
  check('web storage holds mm_lang=fr', webStorage.getItem('mm_lang') === 'fr', `got ${JSON.stringify(webStorage.getItem('mm_lang'))}`);

  // Simulate app restart: fresh modules + init() reads storage
  purgeLocalizationCache();
  const { lm: LM2 } = loadLocalization();
  await LM2.languageManager.init();
  check('fresh languageManager.init() restores fr', LM2.languageManager.language === 'fr', `got ${LM2.languageManager.language}`);

  // 3. Parameterized translations
  console.log('\n[3] Parameterized translations');
  const { index: L3 } = loadLocalization();
  const t3 = L3.i18n.t.bind(L3.i18n);
  const setLang3 = L3.i18n.setLanguage.bind(L3.i18n);
  const paramCases = [
    ['en', 'productDetail.salesCount', { count: 7 }, '7 sales'],
    ['en', 'productDetail.moreInCategory', { category: 'Shoes' }, 'More in Shoes'],
    ['en', 'signup.ageVerified', { age: 21 }, '✓ 21 years old (18+ verified)'],
    ['ht', 'productDetail.salesCount', { count: 3 }, '3 vend'],
    ['ht', 'signup.ageMinor', { age: 15 }, '! 15 ane (Fòk ou gen 18+)'],
    ['ht', 'signup.allSet', { name: ', Jean' }, 'Tout pare, Jean!'],
    ['fr', 'productDetail.salesCount', { count: 12 }, '12 ventes'],
    ['fr', 'notifSettings.enabledToast', { name: 'Messages' }, 'Notifications Messages activées'],
    ['fr', 'chat.theyTyping', { name: 'Marie' }, 'Marie est en train d\'écrire…'],
    ['en', 'productDetail.shareMessage', { name: 'Table', price: '1,500' }, 'Check out "Table" on MaurMaket — 1,500 G'],
  ];
  for (const [lang, key, params, expected] of paramCases) {
    await setLang3(lang);
    const got = t3(key, params);
    check(`${lang}: ${key}`, got === expected, `got ${JSON.stringify(got)}`);
  }

  // 4. Fallback chain
  console.log('\n[4] Fallback chain (current → English → raw key)');
  await setLang3('ht');
  const rawKey = t3('totally.madeUp.key');
  check('nonexistent key returns raw key', rawKey === 'totally.madeUp.key', `got ${JSON.stringify(rawKey)}`);

  // English fallback: simulate a real gap by temporarily removing one key
  // from the ht dictionary the provider holds (proves the ?? messages.en path)
  const { index: L4 } = loadLocalization();
  const jsonProv = require(path.join(ROOT, 'src/localization/providers/json.ts'));
  const htDict = jsonProv.jsonProvider && null; // provider holds dicts internally
  // Instead: delete from the imported ht messages object the provider uses
  // (same object reference the provider reads from)
  const htMessages = require(path.join(ROOT, 'messages/ht.json'));
  const saved = htMessages['settings.notifications'];
  delete htMessages['settings.notifications'];
  await setLang3('ht');
  const fellBack = t3('settings.notifications');
  htMessages['settings.notifications'] = saved; // restore
  check('missing key in current language falls back to English',
    fellBack === 'Notifications', `got ${JSON.stringify(fellBack)}`);

  // 5. Module-level factory pattern
  console.log('\n[5] Module-level factories (signup wizard pattern)');
  await setLang3('ht');
  const steps = { name: t3('signup.aboutYou'), contact: t3('signup.contactStep'), age: t3('signup.ageStep') };
  check('signup step labels resolve in ht',
    steps.name === 'Ankèt sou ou' || (steps.name !== 'About you' && steps.age === 'Laj'),
    JSON.stringify(steps));
  const purposes = { buy: t3('signup.purposeBuyTitle'), sell: t3('signup.purposeSellTitle') };
  check('signup purpose titles resolve in ht',
    purposes.buy === 'Dekouvri e achte' && purposes.sell === 'Bati yon boutik',
    JSON.stringify(purposes));

  // 6. Raw-key leak invariant
  console.log('\n[6] Raw-key leak invariant (no translation value looks like a key)');
  const keyShape = /^[a-z][a-zA-Z0-9]*\.[a-zA-Z0-9_.]+$/;
  let leaked = 0;
  for (const file of ['en.json', 'ht.json', 'fr.json']) {
    const msgs = JSON.parse(fs.readFileSync(path.join(ROOT, 'messages', file), 'utf8'));
    for (const [k, v] of Object.entries(msgs)) {
      if (typeof v === 'string' && keyShape.test(v.trim())) {
        leaked++;
        if (leaked <= 5) console.log(`    leak: ${file} ${k} = ${JSON.stringify(v)}`);
      }
    }
  }
  check('no message value is itself a raw key', leaked === 0, `${leaked} leaked`);

  // 7. No empty values
  console.log('\n[7] No empty translation values');
  let empties = 0;
  for (const file of ['en.json', 'ht.json', 'fr.json']) {
    const msgs = JSON.parse(fs.readFileSync(path.join(ROOT, 'messages', file), 'utf8'));
    for (const [k, v] of Object.entries(msgs)) {
      if (typeof v === 'string' && v.trim() === '') {
        empties++;
        if (empties <= 5) console.log(`    empty: ${file} ${k}`);
      }
    }
  }
  check('no empty values in any language', empties === 0, `${empties} empty`);

  // ══════════════════════════════════════════════════════════════
  console.log('\n[native storage path — Platform.OS = native (SecureStore seam)]');
  const webLangBeforeNative = webStorage.getItem('mm_lang');
  seam.os = 'native';
  purgeLocalizationCache();
  const { index: LN, lm: LMN } = loadLocalization();
  const setLangN = LN.i18n.setLanguage.bind(LN.i18n);

  await setLangN('ht');
  check('native seam persists mm_lang=ht', ssStore.get('mm_lang') === 'ht', `got ${JSON.stringify(ssStore.get('mm_lang'))}`);
  check('web storage NOT touched by native path', webStorage.getItem('mm_lang') === webLangBeforeNative, `got ${JSON.stringify(webStorage.getItem('mm_lang'))}, expected unchanged ${JSON.stringify(webLangBeforeNative)}`);

  // Native restart simulation
  purgeLocalizationCache();
  const { lm: LMN2 } = loadLocalization();
  await LMN2.languageManager.init();
  check('fresh native init() restores ht', LMN2.languageManager.language === 'ht', `got ${LMN2.languageManager.language}`);

  // ── Static invariant: Alert/toast string-literal audit ──────────
  console.log('\n[8] Static invariant: no untranslated Alert.alert literals in migrated screens');
  const { execSync } = require('child_process');
  const screensToCheck = [
    'src/screens/PrivacySettingsScreen.tsx',
    'src/screens/NotificationsSettingsScreen.tsx',
    'src/screens/SettingsEditScreen.tsx',
    'src/screens/ProductDetailScreen.tsx',
    'src/screens/FeedScreen.tsx',
    'src/screens/WishlistScreen.tsx',
    'src/screens/AccountDashboardScreen.tsx',
    'src/screens/MeScreen.tsx',
    'src/screens/ChatScreen.tsx',
    'src/screens/onboarding/OriginalSignupWizard.tsx',
  ];
  let alertLeaks = 0;
  for (const f of screensToCheck) {
    const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
    // Alert.alert with a string-literal first arg (title)
    const matches = src.match(/Alert\.alert\(\s*['"][A-Z][^'"]{2,}['"]/g) || [];
    if (matches.length) {
      alertLeaks += matches.length;
      console.log(`    ${f}: ${matches.length} literal Alert title(s)`);
    }
  }
  check('no literal Alert.alert titles in migrated screens', alertLeaks === 0, `${alertLeaks} leaks`);

  // ── Summary ──────────────────────────────────────────────────────
  console.log(`\n══════════════════════════════════════════`);
  console.log(`  Localization runtime validation`);
  console.log(`  PASSED: ${passed}   FAILED: ${failed}`);
  if (failed > 0) {
    console.log('\nFailures:');
    for (const f of failures) console.log(`  - ${f.name}${f.detail ? ' — ' + f.detail : ''}`);
  }
  console.log(`══════════════════════════════════════════`);
  process.exit(failed > 0 ? 1 : 0);
})().catch(err => {
  console.error('Runtime validation crashed:', err);
  process.exit(1);
});
